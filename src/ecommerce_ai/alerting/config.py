# 退款/退货类指标关键词（据此选择「节后窗口」而非「预热窗口」）
REFUND_METRIC_HINTS = ("退款", "退货", "refund", "return")

# ---- 时序检测：同周几基线 ----
# 电商存在周内节律（周一低、周六高）。用「全历史中位数」作基线会把常态波动误报为异常。
# 同周几点 ≥ MIN_WEEKDAY_SAMPLES（含最新值）才启用，否则回退全历史基线（保证不退化）。
MIN_WEEKDAY_SAMPLES = 4

# ---- 时序检测：环比突变判据（二阶检测）----
# z-score 受 sigma 影响：波动大的指标（如曝光量）即使真断崖也可能落在 3σ 内。
# 但若用「固定阈值如 40%」判环比，会误伤天然波动大的比率型指标——
# 转化率 0.030→0.018 就是 -40%，纯属日常波动。
# 正确做法：对「变化率本身」再做一次稳健 z 检验，与**该指标自身的历史环比分布**比较。
TRAIL_CHANGE_MIN = 0.15   # 最低幅度门槛（防止微小变化的 z 值虚高）

# 节日窗口内的「预期内」容忍上限：
#   窗口内 |z| < 此值 → 视为预期内波动，降为 P2（提示级，不干扰注意力）；
#   窗口内 |z| ≥ 此值 → 视为「幅度显著超出节日正常范围」的真异常，保留原级别 + 特别标注。
# 这是「窗口豁免」不掩盖真异常的关键——窗口只知道方向，幅度才是判断依据。
FESTIVAL_TOLERANCE_Z = 8.0

# 最小样本量
MIN_GROUP = 5          # 截面分组至少行数
MIN_TEMPORAL = 7       # 时序基线至少天数（含最新值则需 >=8 个点）

# 灵敏度 -> z 阈值（越大越保守，误报少但可能漏报）
SENSITIVITY_Z = {"conservative": 4.0, "standard": 3.0, "sensitive": 2.0}

# 跨次环比大跌阈值（相对变化）
CROSS_UPLOAD_DROP = 0.30


def canonical_metric(col_name: str) -> str:
    """把任意指标列名映射到规范名（找不到则返回原名）。"""
    return _SYN_TO_CANON.get(str(col_name).strip().lower(), col_name)
